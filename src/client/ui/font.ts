/**
 * 烘焙好的字模：`bits[code * GLYPH_H + row]` 的低 5 位是那一行的点阵，
 * 最高位（第 4 位）对应最左一列。
 *
 * 用扁平 Uint8Array 而不是每次去查 Record<string, string>：一行 F3 文本
 * 有几十个字符，每帧十几行，一秒下来是几万次查表 + 字符串索引。
 */
export interface Font {
  readonly bits: Uint8Array;
  /** ASCII 码的有效范围 */
  readonly first: number;
  readonly last: number;
}

let cached: Font | null = null;

export function buildFont(): Font {
  if (cached !== null) return cached;
  const first = 32;
  const last = 126;
  const bits = new Uint8Array((last - first + 1) * GLYPH_H);
  const fallback = GLYPHS['?']!;
  for (let code = first; code <= last; code++) {
    const rows = (GLYPHS[String.fromCharCode(code)] ?? fallback).split('/');
    for (let r = 0; r < GLYPH_H; r++) {
      const row = rows[r] ?? '.....';
      let v = 0;
      for (let c = 0; c < GLYPH_W; c++) {
        if (row[c] === '#') v |= 1 << (GLYPH_W - 1 - c);
      }
      bits[(code - first) * GLYPH_H + r] = v;
    }
  }
  cached = { bits, first, last };
  return cached;
}

/** 一段文字画出来有多宽（虚拟像素） */
export function textWidth(text: string, scale = 1): number {
  return text.length * GLYPH_ADVANCE * scale;
}
